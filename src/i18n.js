export function translateAlert(text) {
  if (currentLang === 'zh-Hant' || !text) return text;
  const rules = ALERT_MAP[currentLang];
  if (!rules) return text;
  let out = text;
  for (const [src, dst] of rules) {
    if (out.includes(src)) out = out.replaceAll(src, dst);
  }
  return out;
}
